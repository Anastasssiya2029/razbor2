function sameElementSet(left: readonly SevenKElementId[], right: readonly SevenKElementId[]): boolean {
  return left.length === right.length && left.every((elementId) => right.includes(elementId));
}

export function findBundleRule(
  keyElements: readonly SevenKElementId[],
  supportingElements: readonly SevenKElementId[],
): BundleRule | null {
  return BUNDLE_RULES.find(
    (rule) => sameElementSet(rule.keyElements, keyElements)
      && sameElementSet(rule.supportingElements, supportingElements),
  ) ?? null;
}
